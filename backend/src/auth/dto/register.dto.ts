import {
  IsEmail,
  IsIn,
  IsOptional,
  IsString,
  MinLength,
} from 'class-validator';

export class RegisterDto {
  @IsEmail()
  email: string;

  @IsString()
  @MinLength(6)
  password: string;

  @IsString()
  @MinLength(2)
  name: string;

  @IsOptional()
  @IsIn(['USER', 'MERCHANT'])
  role?: 'USER' | 'MERCHANT';

  @IsOptional()
  @IsString()
  city?: string;
}
